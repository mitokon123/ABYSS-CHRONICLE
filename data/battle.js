/**
 * battle.js
 * 戦闘に関する数値・計算パラメータ。ゲームバランスの中心。
 *
 * ▼ ダメージ計算式（すべてこのファイルの数値で調整可能）
 *
 *   技のとき   基礎 = 攻撃力 × skill.attackFactor  + 技威力 × skill.powerFactor - 防御力 × defenseFactor
 *              （係数は技の種類ごと。damage.byKind にある種類はそちらを使う）
 *   通常攻撃   基礎 = 攻撃力 × normal.attackFactor + normal.power             - 防御力 × defenseFactor
 *   基礎 = max(0, 基礎)
 *   ダメージ = floor( 基礎 × 属性倍率 × クリティカル倍率 × 防御コマンド倍率
 *                     × 特性・装備の倍率 × 乱数(randomMin〜randomMax) )
 *   ダメージ = max(minDamage, ダメージ)   ※属性無効のときは 0
 *
 *   「通常攻撃」は normalAttackSkill で指定した技だけ。それ以外はすべて「技」の式
 *   （体当たりや噛みつくのような無属性の技も、技の式で計算する）。
 *
 * ▼ 属性倍率
 *   耐性が0以上 … 倍率 = 1 - 耐性 × resistance.resistStep
 *   耐性がマイナス … 倍率 = 1 + |耐性| × resistance.weaknessStep
 *   耐性は data/monsters.js の resistances（-5〜10）。
 *     -5 → ×2.00（2倍）   0 → ×1.00   +9 → ×0.10   +10 → 無効
 *   耐性が immuneAt 以上、または immunities に入っている属性はダメージ0。
 *   無属性（elements.js の physical:true）は耐性の影響を受けない。
 *
 * ▼ クリティカル
 *   確率 = critical.baseRate + 技の criticalBonus
 *   当たると damage に critical.multiplier を掛ける。
 *
 * ▼ 命中
 *   技に accuracy が書かれていればその値、無ければ defaultAccuracy。
 *
 * ▼ 行動順
 *   全員の行動を決めたあと、素早さの大きい順に行動する。
 *   並べ替えに使う素早さは speedVariance の範囲でぶれる。
 *   speedTieBreak … 素早さが同じときの決め方（"random" / "allyFirst" / "enemyFirst"）
 */
(function (NS) {
  "use strict";

  NS.rawData.battle = {
    damage: {
      /**
       * ▼ 技と通常攻撃で、攻撃力の効き方を分けている（早見表/技.txt）
       *   通常攻撃 … 攻撃力 × 0.75。殴りは攻撃力に強く依存。終盤は通常攻撃が主役になる想定
       *   技       … 攻撃力 × 0.40 + 威力 × 1.35。技の火力は攻撃力にあまり依存させず、
       *              技の段階（tier）と装備の倍率で伸ばす。低攻撃力の種族でも上位技で戦える
       *   同じ攻撃力なら、威力15の基本技は通常攻撃より少し強く（攻20で 28 vs 15）、
       *   威力が上がるほど差が開く。
       *
       * ▼ 攻撃と防御の比が「防御の値打ち」を決める
       *   防御1点で打ち消せるのは 攻撃 defenseFactor ÷ attackFactor 点ぶん。
       *   通常攻撃なら 0.40点ぶん、技なら 0.75点ぶん（技は攻撃力の係数が小さいので、
       *   防御が技に対して相対的によく効く）。
       *
       * ▼ defenseFactor をこれ以上上げてはいけない
       *   ここは相手のHPが大きいほど効く。主はHP倍率で3〜4倍に膨らんでいるので、
       *   雑魚戦より**主の戦いに強く効く**。
       *   0.35 まで上げたときは、深層の主の勝率が 24% → 1% まで落ちた。
       *   触ったら必ず主4体の勝率を測り直すこと。
       *
       * ▼ 技の係数はプレイヤー側に偏って効く
       *   主の行動は通常攻撃が多いので、skill 側を上げても主はあまり得をせず、
       *   毎ターン技を撃つこちらだけが得をする。強さの調整に使うなら、
       *   「敵が得をしない上方修正」だと分かった上で使うこと。
       */
      skill:  { attackFactor: 0.40, powerFactor: 1.35 },   // 技（種類の係数が無いとき）
      /**
       * 通常攻撃（normalAttackSkill）。power は攻撃力に関係なく足す小さな上乗せ（α-10）。
       *   最序盤は攻撃力が5〜8しかなく、攻撃力だけだと2〜3しか出ない。威力を持つ技
       *   （体当たり）と7倍の差が開いていたので、3を足して差を2倍ほどに縮めた。
       *   敵の通常攻撃にも同じだけ足される（最序盤の敵が少し痛くなる）。中盤以降はほぼ効かない
       */
      normal: { attackFactor: 0.75, power: 3 },
      /**
       * ▼ 技の種類ごとの係数（skills.js の kind。種類は data/categories.js の skillKind）
       *   書いた種類はこちらを使い、書いていない種類・kind の無い技は上の skill を使う。
       *   2026-09-27 作者が決定（技の種類.md の 3.）。
       *
       *   ・攻撃力の低い種族は、どの種類でも以前（0.40 / 1.35）とほぼ同じ。
       *     差が出るのは攻撃力の高い種族：斬撃・体技が伸び、共鳴・ブレスが下がる
       *   ・斬撃は最初 0.75 / 1.00（通常攻撃と同じ攻撃係数）だったが、終盤に強すぎるので
       *     0.65 / 1.10 に下げた。攻400なら 斬撃 威力60 ＝ 236 で、共鳴の最上位 威力160 ＝ 250 を下回る
       *   ★ 斬撃・体技は攻撃力にそのまま伸びるので、終盤ほど強い。
       *     新しい斬撃・体技の威力は、共鳴より低く作ること
       *   ★ 早見表/技.txt の tier2〜4（共鳴）の威力は「威力×1.35」のころに決めたもの。
       *     共鳴は ×1.50 になったので、足すときに見直す
       */
      //   defenseFactor … その種類だけ防御の引き方を変える（書かなければ下の共通 0.30）。
      //     共鳴・ブレスは 0.15（半分）。2026-09-29 作者の判断：属性技が9割なので、
      //     防御より「耐性」が守りの中心になるようにする。まず半分で試し、足りなければ 0（無視）へ
      byKind: {
        resonance: { attackFactor: 0.25, powerFactor: 1.50, defenseFactor: 0.15 },  // 共鳴：攻撃力にあまり頼らず、威力が効く
        breath:    { attackFactor: 0.30, powerFactor: 1.35, defenseFactor: 0.15 },  // ブレス：全体・状態異常のぶん控えめ
        body:      { attackFactor: 0.55, powerFactor: 1.25 },  // 体技：攻撃力も威力もよく効く
        slash:     { attackFactor: 0.65, powerFactor: 1.10 },  // 斬撃：攻撃力にいちばん大きく頼る
        dance:     { attackFactor: 0.40, powerFactor: 1.35 }   // 踊り：未定（いずれ技ごとの専用の式）。今は以前の値
      },
      defenseFactor: 0.30,  // 防御力に掛ける係数（通常攻撃・体技・斬撃。共鳴とブレスは byKind で 0.15）
      randomMin: 0.9,
      randomMax: 1.1,
      minDamage: 1
    },

    /**
     * 敵が狙う位置の重み（盤面の左から順）。
     * 前に置いた仲間ほど狙われる。並び順が「誰を盾にするか」の選択になる。
     * 盤面に出ている数が少ないときは、その数だけで割り直す。
     */
    targetWeights: [0.50, 0.35, 0.15],

    critical: {
      baseRate: 0.03,   // 全キャラ共通のクリティカル率
      multiplier: 2.0   // クリティカル時の倍率
    },

    /**
     * 属性耐性。プラスとマイナスで1あたりの効き方を変えている。
     *   プラス側 … 1につき resistStep だけ軽くなる（+10 で完全無効）
     *   マイナス側 … 1につき weaknessStep だけ重くなる（-5 で2倍）
     * 弱点のほうが1あたりの動きが大きいので、少ない値でも効きが分かる。
     *
     * ★ maxValue / minValue は「種族の値＋装備などの合計」を挟む範囲。
     *   +10 が完全無効なので、そこから先はいくら足しても意味がない。
     *   挟まないと「毒8のスライムに毒よけの護符(+7)で15」のような、
     *   数字だけ伸びて効果が変わらない表示になってしまう。
     *   状態異常の耐性もこの範囲を使う（仕組みを2つにしない）。
     */
    resistance: {
      resistStep: 0.10,   // 耐性1あたりの軽減量（+9 で0.1倍まで下がる）
      weaknessStep: 0.20, // 弱点1あたりの増加量（-5 で2.0倍）
      immuneAt: 10,       // この値以上は完全無効（immunities と同じ扱い）
      maxValue: 10,       // 合計の上限。装備で足してもここで止まる
      minValue: -5,       // 合計の下限。ここが最大の弱点（2.0倍）
      minMultiplier: 0    // 倍率の下限（マイナス倍率を防ぐ）
    },

    /**
     * 防御コマンド。
     * 選んだターンの間、受けるダメージが multiplier 倍になる（属性もクリティカルも問わない）。
     * 次のターンが始まると解除される。
     */
    defend: { multiplier: 0.5 },

    /**
     * 敵の行動の決め方。
     * skillRate の確率で技を使い、それ以外は通常攻撃をする。
     * （序盤の敵なので低めにしてある）
     */
    enemyAi: { skillRate: 0.25 },

    speedVariance: { min: 0.8, max: 1.2 },  // 行動順を決めるときの素早さのぶれ

    normalAttackSkill: "normalAttack",  // 「攻撃」コマンドで使う技id
    defaultAccuracy: 1.0,               // accuracy が書かれていない技の命中率

    speedTieBreak: "random",
    fleeSuccessRate: 0.6,

    // 主（ボス）の戦いから逃げられるか。
    //   全ボス共通の決まりにしてある。ボスごとの設定にしていたころは、
    //   ボスを足すときに書き忘れると逃げられる主ができてしまった。
    //   ここが false のあいだ、ボス戦のコマンドに「逃げる」は出ない
    bossCanFlee: false,

    /**
     * 主として立ちはだかっているあいだ、効かない状態異常（全ボス共通）。
     * 逃走と同じで、ボスごとに書くと足すときに書き忘れるので1か所にまとめてある。
     * 仲間に迎えたときは、その種族そのままの耐性に戻る（data/monsters.js の statusResist）。
     *
     *   即死     … 15%の抽選1回で主が消えると、そこまでの設計が無意味になる
     *   封印・盲目 … 主は決まった手順（actionPattern）で動くのが戦いの骨格なので、
     *               技を止める・当たらなくするの2つは、その骨格ごと崩してしまう
     *
     * ★ 毒は共通のリストから外した（α-8）。ただし揺籃の穴の主4体は、
     *   data/bosses.js の immuneToStatus で1体ずつ毒を無効にしているので、いまは毒の効く主はいない。
     *   HPが4桁になる主なら、毒の上限（data/statuses.js の turnDamage.max＝50）で 5%以下に収まるので、
     *   そういう主には書かなくてよい。★ 上限を上げるときは、主の戦いが毒1つで別物にならないか必ず測ること。
     *
     * ★ ここに無い状態異常（麻痺・眠り・呪い）は、主ごとに足さない限り主にも効く（種族の耐性は効く）。
     *   主ごとに足したいものがあれば data/bosses.js の immuneToStatus に書く（両方が効く）。
     *   眠りは2〜4ターン完全に止めるので、封印・盲目より手順を崩しやすい。揺籃の穴の主は
     *   最初の地方なので効くままにしてある（作者の判断）。次の地方からは、毒と同じように
     *   主ごとに immuneToStatus へ足して効かなくしていく
     */
    bossImmuneToStatus: ["instantDeath", "seal", "blind"]
  };
})(window.MyGame);
